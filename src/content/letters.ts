export const letters: LetterPuzzle[] = drafts.map(
  (
    [id, category, texts, falseIndex, correction, explanation, title, url],
    i,
  ) => {
    const claims = texts.map((text, n) => ({
      id: `${id}-${n + 1}`,
      text,
    })) as LetterPuzzle["claims"];
    return {
      id,
      category,
      difficulty: i % 6 < 2 ? "easy" : i % 6 < 5 ? "medium" : "hard",
      recipientId: recipients[category].id,
      claims,
      falseClaimId: claims[falseIndex].id,
      correction,
      explanation,
      sources: [{ title, url, supportedClaimIds: claims.map((c) => c.id) }],
      verificationStatus: "needs-editorial-review",
      reactionCorrect:
        "A little truth makes the long night brighter. Thank you, clerk.",
      reactionIncorrect:
        "No trouble, dear clerk. Even the post takes a scenic route sometimes.",
    };
  },
);
export const letterById = Object.fromEntries(letters.map((p) => [p.id, p]));
